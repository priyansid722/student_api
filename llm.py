"""LLM Integration module using the official Google GenAI SDK.

This module connects FastAPI to Google Gemini (gemini-2.5-flash by default)
to provide a natural language question-answering interface over the student records.

Key Architecture / Security Features:
1. Grounded Context (RAG): Backend code executes the SQL query, not the AI model.
   The AI model NEVER receives direct SQL execution access.
2. Controlled Context Window: Retrieves up to 200 records formatted as JSON.
3. Strict System Prompt: The model is instructed to answer ONLY from the provided records
   and to explicitly decline answering if information is missing.
"""

import json
import os
from dotenv import load_dotenv
from google import genai
from database import get_conn

# Load environment variables from .env if present
load_dotenv()


def ask_about_students(question: str) -> str:
    """Query Google Gemini with student data context to answer a natural language question.

    Args:
        question: The user's query about students in the database.

    Returns:
        A concise answer string generated by Gemini based strictly on the SQLite records.

    Raises:
        RuntimeError: If GEMINI_API_KEY is missing or empty.
    """
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        raise RuntimeError("GEMINI_API_KEY is not set")

    # Backend code (not the AI) fetches the records. The AI never touches SQL.
    with get_conn() as conn:
        rows = [dict(r) for r in conn.execute("SELECT * FROM students LIMIT 200").fetchall()]

    context = json.dumps(rows, indent=1)
    prompt = (
        "You are an assistant for a student database.\n"
        "Answer ONLY using the records below. If the answer is not in the records, "
        "say you cannot find it. Be short and clear.\n\n"
        f"Total students: {len(rows)}\n"
        f"Records (JSON):\n{context}\n\n"
        f"Question: {question}"
    )

    client = genai.Client(api_key=api_key)
    model = os.getenv("GEMINI_MODEL", "gemini-2.5-flash")
    response = client.models.generate_content(model=model, contents=prompt)
    return response.text
